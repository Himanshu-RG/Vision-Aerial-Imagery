"""M8: experiment registry -- one CSV row per (run, condition) across all evaluated runs.

Usage:
    python scripts/build_registry.py      # writes outputs/metrics/registry.csv and reports/generated/registry.md
Maps conditions to the master-prompt experiment IDs (E1-E8) and records provenance per run.
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]


def experiment_id(cond: str) -> str:
    if cond == "full":
        return "E1"
    if cond.startswith("sel:frequency"):
        return "E2"
    if cond.startswith("sel:random") or cond == "random_matched":
        return "E3"
    if cond.startswith("sel:") and cond.split(":")[1] in ("clip_openai_b32", "remoteclip_b32"):
        return "E4"
    if cond.startswith("sel:") and cond.split(":")[1].endswith(("_gl", "_local")):
        return "E6"
    if cond.startswith("set:m6_retain"):
        return "E7"
    if cond.startswith("set:m6_"):
        return "E8"
    if cond.startswith("oracle"):
        return "oracle"
    return "other"


def main() -> int:
    rows = []
    for d in sorted((REPO_ROOT / "outputs" / "metrics").iterdir()):
        mf, rc = d / "metrics.json", d / "run_config.json"
        if not (mf.is_file() and rc.is_file()) or "_vs_" in d.name:
            continue
        m, cfg = json.loads(mf.read_text(encoding="utf-8")), json.loads(rc.read_text(encoding="utf-8"))
        for cond in cfg["config"]["conditions"]:
            r = m["conditions"].get(cond)
            if r is None:
                continue
            s, a = r["standard"], r["source_aware"]
            rows.append({"run_id": m["run_id"], "experiment": experiment_id(cond), "condition": cond,
                         "split": cfg["config"]["split"], "n_images": len(cfg["image_ids"]), "host": cfg["host"],
                         "git_commit": cfg["git_commit"][:7], "git_dirty": cfg["git_dirty"], "n_failed": r["n_failed_or_missing"],
                         "vocab_size_mean": round(r["vocab_size_mean"] or 0, 2), "AP50_std": round(s["AP50@900"], 4),
                         "AP50_src": round(a["AP50@900"], 4), "AP_std": round(s["AP@900"], 4), "AR900_std": round(s["AR@900"], 4),
                         "R50_small_std": round(s["R50_small"], 4),
                         "F1@0.35_std": round(s["operating_points"]["@0.35"]["f1"], 4) if "operating_points" in s else "",
                         "latency_median_ms": round((r.get("latency_ms") or {}).get("median") or 0, 1)})
    out = REPO_ROOT / "outputs" / "metrics" / "registry.csv"
    with out.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    L = ["# Experiment registry (generated by `scripts/build_registry.py`; dev split only so far)", "",
         "| run | exp | condition | n | vocab | AP50 std | AP50 src-aware | AR@900 | F1@0.35 | latency ms | git |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['run_id']} | {r['experiment']} | {r['condition']} | {r['n_images']} | {r['vocab_size_mean']} | {r['AP50_std']} "
                 f"| {r['AP50_src']} | {r['AR900_std']} | {r['F1@0.35_std'] or '–'} | {r['latency_median_ms']} | {r['git_commit']} |")
    (REPO_ROOT / "reports" / "generated" / "registry.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} rows -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
