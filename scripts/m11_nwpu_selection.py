"""M11 part 2: detector-free selection quality on NWPU VHR-10 (frozen selectors, D45).

Usage:
    python scripts/m11_nwpu_selection.py
Per selection rule: mean size, image-mean class recall, object-weighted coverage, share of selected classes outside
the 9 annotated ids, and the most frequent selected non-annotated classes (e.g. near-synonyms such as
"Small Car" for "vehicle"), overall and for the colour-infrared (Vaihingen-derived) subgroup.
Writes outputs/metrics/m11_nwpu/selection.json and reports/generated/M11_nwpu_selection.md.
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from aerial_ovd.data.splits import NWPU_TO_LAE, gt_path  # noqa: E402
from aerial_ovd.utils.paths import get_store  # noqa: E402
from aerial_ovd.vocabulary.retention import topk  # noqa: E402

SEL = REPO_ROOT / "outputs/selection/nwpu"


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    gt = json.loads(gt_path(get_store(), "nwpu").read_text(encoding="utf-8"))
    man = {int(r["image_id"]): r for r in csv.DictReader((REPO_ROOT / "data/manifests/nwpu_manifest.csv").open(encoding="utf-8"))}
    name = {int(r["category_id"]): r["raw_name"] for r in csv.DictReader((REPO_ROOT / "data/manifests/lae80c_vocabulary.csv").open(encoding="utf-8"))}
    rc = np.load(SEL / "remoteclip_b32.npz")
    ids, cats = [int(i) for i in rc["image_ids"]], [int(c) for c in rc["cat_ids"]]
    cidx = {c: j for j, c in enumerate(cats)}
    N = np.zeros((len(ids), len(cats)))
    row = {i: k for k, i in enumerate(ids)}
    for a in gt["annotations"]:
        N[row[a["image_id"]], cidx[a["category_id"]]] += 1
    annotated = np.isin(cats, list(NWPU_TO_LAE.values()))
    cir = np.array([man[i]["cir"] == "1" for i in ids])
    rules = {"oracle_gt": N > 0}
    for sel, ks in (("frequency", (8,)), ("clip_openai_b32", (8, 20)), ("remoteclip_b32", (3, 8))):
        S = np.load(SEL / f"{sel}.npz")["scores"]
        for k in ks:
            rules[f"{sel} top-{k}"] = np.stack([topk(s, k) for s in S])
    rules["headline (D34, frozen)"] = np.load(SEL / "headline_d34.npz")["selected"]
    out = {"n_images": len(ids), "n_cir": int(cir.sum()), "rules": {}}
    for k, M in rules.items():
        r = {}
        for grp, g in (("all", np.ones(len(ids), bool)), ("cir", cir), ("non_cir", ~cir)):
            Mg, Ng = M[g], N[g]
            r[grp] = {"mean_size": float(Mg.sum(1).mean()),
                      "image_mean_recall": float(np.mean([(Mg[i] & (Ng[i] > 0)).sum() / (Ng[i] > 0).sum() for i in range(len(Mg))])),
                      "object_weighted": float((Ng * Mg).sum() / Ng.sum()),
                      "selected_not_annotated_share": float(np.mean([(Mg[i] & ~annotated).sum() / Mg[i].sum() for i in range(len(Mg))]))}
        c = Counter(name[cats[j]] for i in range(len(ids)) for j in np.where(M[i] & ~annotated)[0])
        r["top_non_annotated"] = c.most_common(8)
        out["rules"][k] = r
    dst = REPO_ROOT / "outputs/metrics/m11_nwpu"
    dst.mkdir(parents=True, exist_ok=True)
    (dst / "selection.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8", newline="\n")
    L = ["# M11 NWPU VHR-10 selection quality (generated by `scripts/m11_nwpu_selection.py`)", "",
         f"{out['n_images']} images (ship-only images removed), {out['n_cir']} colour-infrared. All selectors frozen (D45); "
         "80-class vocabulary; 9 annotated classes.", "",
         "| rule | mean size | image recall | object-weighted | selected but not annotated | CIR: object-weighted | non-CIR: object-weighted |",
         "|---|---|---|---|---|---|---|"]
    for k, r in out["rules"].items():
        a = r["all"]
        L.append(f"| {k} | {a['mean_size']:.2f} | {a['image_mean_recall']:.3f} | {a['object_weighted']:.3f} | {a['selected_not_annotated_share']:.2f} "
                 f"| {r['cir']['object_weighted']:.3f} | {r['non_cir']['object_weighted']:.3f} |")
    L += ["", "Most frequent selected classes that are not NWPU's annotated classes (n images):", ""]
    L += [f"- **{k}:** " + "; ".join(f"{n} ({c})" for n, c in r["top_non_annotated"]) for k, r in out["rules"].items() if k != "oracle_gt"]
    (REPO_ROOT / "reports/generated/M11_nwpu_selection.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
