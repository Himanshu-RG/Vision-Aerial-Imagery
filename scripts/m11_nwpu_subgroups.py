"""M11 part 2: AP50 on NWPU subgroups (colour-infrared / Vaihingen-derived vs the rest), from a run's predictions.

Usage:
    python scripts/m11_nwpu_subgroups.py outputs/predictions/<m11_nwpu run>
Writes outputs/metrics/m11_nwpu/subgroups.json and reports/generated/M11_nwpu_subgroups.md (small, committed).
Also reports per-class AP50 for every condition (9 classes).
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from aerial_ovd.data.splits import NWPU_TO_LAE, gt_path  # noqa: E402
from aerial_ovd.evaluation.coco_eval import _ap_one_category, ap50_from_matches, per_image_matches  # noqa: E402
from aerial_ovd.utils.paths import get_store  # noqa: E402
from evaluate_run import read_records  # noqa: E402


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    run = Path(sys.argv[1])
    meta = json.loads((run / "run_config.json").read_text(encoding="utf-8"))
    assert meta["config"]["split"] == "nwpu"
    ids = meta["image_ids"]
    gt = json.loads(gt_path(get_store(), "nwpu").read_text(encoding="utf-8"))
    man = {int(r["image_id"]): r for r in csv.DictReader((REPO_ROOT / "data/manifests/nwpu_manifest.csv").open(encoding="utf-8"))}
    name = {int(r["category_id"]): r["raw_name"] for r in csv.DictReader((REPO_ROOT / "data/manifests/lae80c_vocabulary.csv").open(encoding="utf-8"))}
    groups = {"all": ids, "cir": [i for i in ids if man[i]["cir"] == "1"], "non_cir": [i for i in ids if man[i]["cir"] != "1"]}
    out = {"run_id": meta["run_id"], "n": {g: len(v) for g, v in groups.items()}, "conditions": {}}
    for cond in meta["config"]["conditions"]:
        recs = read_records(run / (cond.replace(":", "__") + ".jsonl"))
        preds = [{"image_id": r["image_id"], "category_id": d[0], "score": d[1], "bbox": d[2:6]}
                 for r in recs.values() if r.get("status") == "ok" for d in r["detections"]]
        m = per_image_matches(gt, preds, ids)
        res = {g: ap50_from_matches(m, v) for g, v in groups.items()}
        pc = {}
        for k in NWPU_TO_LAE.values():
            parts = list(m["per_cat"][k].values())
            npig = sum(p[3] for p in parts)
            pc[name[k]] = _ap_one_category(np.concatenate([p[0] for p in parts]), np.concatenate([p[1] for p in parts]),
                                           np.concatenate([p[2] for p in parts]), npig) if npig else None
        out["conditions"][cond] = {"AP50": res, "per_class_AP50": pc}
        print(cond, {g: round(v, 4) for g, v in res.items()}, flush=True)
    dst = REPO_ROOT / "outputs/metrics/m11_nwpu"
    dst.mkdir(parents=True, exist_ok=True)
    (dst / "subgroups.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8", newline="\n")
    classes = [name[k] for k in NWPU_TO_LAE.values()]
    L = [f"# M11 NWPU subgroups and per-class AP50 (generated by `scripts/m11_nwpu_subgroups.py` from run `{meta['run_id']}`)", "",
         f"AP50 (maxDets 900, standard = source-aware here). Images: all {out['n']['all']}, colour-infrared (Vaihingen-derived) "
         f"{out['n']['cir']}, other {out['n']['non_cir']}.", "",
         "| condition | all | colour-infrared | other | " + " | ".join(classes) + " |", "|---" * (4 + len(classes)) + "|"]
    for cond, r in out["conditions"].items():
        L.append(f"| {cond} | {r['AP50']['all']:.4f} | {r['AP50']['cir']:.4f} | {r['AP50']['non_cir']:.4f} | "
                 + " | ".join(f"{r['per_class_AP50'][c]:.3f}" for c in classes) + " |")
    (REPO_ROOT / "reports/generated/M11_nwpu_subgroups.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
