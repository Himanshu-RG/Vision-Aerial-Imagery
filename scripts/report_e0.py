"""Generate the E0 result tables (Markdown) from a committed metrics.json. No hand-typed numbers.

Usage:
    python scripts/report_e0.py outputs/metrics/<run_id>   # writes reports/generated/E0_tables.md
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics as st
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ORDER = ["full", "oracle_source", "oracle_gt", "random_matched"]
LABEL = {"full": "full (80 classes)", "oracle_source": "oracle: source label space",
         "oracle_gt": "oracle: GT classes in image", "random_matched": "control: random, size-matched"}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("metrics_dir", type=Path)
    args = ap.parse_args()
    m = json.loads((args.metrics_dir / "metrics.json").read_text(encoding="utf-8"))
    cfg = json.loads((args.metrics_dir / "run_config.json").read_text(encoding="utf-8"))
    vocab = list(csv.DictReader((REPO_ROOT / "data" / "manifests" / "lae80c_vocabulary.csv").open(encoding="utf-8")))
    src = {r["category_id"]: r["source"] for r in vocab}
    conds = [c for c in ORDER if c in m["conditions"]]
    L = [f"# E0 tables (generated by `scripts/report_e0.py` from `{args.metrics_dir.as_posix()}`)", "",
         f"run `{m['run_id']}` · host `{cfg['host']}` · git `{cfg['git_commit'][:7]}` (dirty={cfg['git_dirty']}) · "
         f"torch {cfg['torch']} · {len(cfg['image_ids'])} dev images · checkpoint "
         f"`{cfg['checkpoint_lock']['commit'][:10]}` · bootstrap n={m['bootstrap']['n_boot']}", ""]

    L += ["## Table 1 — accuracy, recall, cost per condition", "",
          "| condition | vocab | tokens | failed | AP50@900 std | AP50@900 src-aware | AP@900 std | AP50@100 std "
          "| AR@900 | R50 small/med/large | latency median ms (fwd) | peak MB |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in conds:
        r = m["conditions"][c]
        s, a = r["standard"], r["source_aware"]
        L.append(f"| {LABEL[c]} | {r['vocab_size_mean']:.1f} | {r['text_tokens_mean']:.0f} | {r['n_failed_or_missing']} "
                 f"| {s['AP50@900']:.4f} | {a['AP50@900']:.4f} | {s['AP@900']:.4f} | {s['AP50@100']:.4f} "
                 f"| {s['AR@900']:.3f} | {s['R50_small']:.3f}/{s['R50_medium']:.3f}/{s['R50_large']:.3f} "
                 f"| {r['latency_ms']['median']:.0f} ({r['latency_ms']['forward_median']:.0f}) | {r['peak_mem_mb_max']:.0f} |")

    L += ["", "## Table 2 — paired image-level bootstrap, AP50@900 difference vs `full` (95% percentile CI)", "",
          "| condition | standard | source-aware |", "|---|---|---|"]
    for c in conds:
        b = m["bootstrap"].get(c)
        if isinstance(b, dict):
            cell = lambda v: (f"{v['diff_point']:+.4f} [{v['ci_low']:+.4f}, {v['ci_high']:+.4f}]"
                              + (" *" if v["ci_excludes_zero"] else ""))
            L.append(f"| {LABEL[c]} | {cell(b['standard'])} | {cell(b['source_aware'])} |")
    L += ["", "`*` = CI excludes 0."]
    diag = [(c, p, v) for c in conds if isinstance(m["bootstrap"].get(c), dict)
            for p, v in m["bootstrap"][c].items() if "bias" in v]
    if diag:
        L += ["", "Bootstrap diagnostics (percentile CI is the pre-registered headline; 'basic' CI shown for robustness):",
              "", "| condition | protocol | bootstrap mean | sd | bias | bias flag | basic CI |", "|---|---|---|---|---|---|---|"]
        for c, p, v in diag:
            L.append(f"| {LABEL[c]} | {p} | {v['boot_mean']:+.4f} | {v['boot_sd']:.4f} | {v['bias']:+.4f} "
                     f"| {v['bias_flag']} | [{v['basic_ci_low']:+.4f}, {v['basic_ci_high']:+.4f}] |")
    else:
        L += ["", "_Bootstrap bias diagnostics not present in this metrics file (evaluated before they were added)._"]

    L += ["", "## Table 3 — mean per-class AP50@900 by source (classes with GT in the sample; std | src-aware)", "",
          "| source | classes | " + " | ".join(LABEL[c] for c in conds) + " |", "|---|---|" + "---|" * len(conds)]
    for s in sorted(set(src.values())):
        ks = [k for k in m["conditions"]["full"]["standard"]["per_class"] if src[k] == s]
        cells = []
        for c in conds:
            vs = [m["conditions"][c][p]["per_class"][k]["AP50"] for p in ("standard", "source_aware") for k in ks]
            n = len(ks)
            cells.append(f"{st.mean(vs[:n]):.3f} \\| {st.mean(vs[n:]):.3f}" if ks else "–")
        L.append(f"| {s} | {len(ks)} | " + " | ".join(cells) + " |")

    out = REPO_ROOT / "reports" / "generated" / "E0_tables.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(out.read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
