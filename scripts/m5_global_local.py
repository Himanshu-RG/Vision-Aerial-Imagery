"""Module 5: compare global, local and global+local vocabulary selection (detector-free).

Usage:
    python scripts/m5_global_local.py --split dev
Reads outputs/selection/<split>/views_<model>.npz (from scripts/run_views.py). For each model it evaluates
all variants: alpha in {0, .25, .5, .75, 1} x agg in {max, mean} x crop grids in {(2), (2,3), (2,3,4)}
(alpha = 1 is the global-only selector of M4). Selection rule fixed BEFORE looking at results (D28):
per model, pick the variant with the highest class-wise ranking mAP on dev; ties -> fewer crops, then
higher alpha, then 'max'.
Writes:
    outputs/metrics/m5_selection_<split>/m5_metrics.json
    reports/generated/M5_selection_tables.md
    outputs/figures/m5_recall_<split>.png
    outputs/selection/<split>/<model>_gl.npz        chosen global+local selector (for detection)
    outputs/selection/<split>/<model>_local.npz     best local-only selector (ablation, for detection)
"""

from __future__ import annotations

import argparse
import csv
import itertools
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from aerial_ovd.utils.paths import get_store  # noqa: E402
from aerial_ovd.vocabulary.selectors import combine_views  # noqa: E402
from evaluate_selection import class_ap, paired_mean_bootstrap  # noqa: E402
from run_detection import load_manifest  # noqa: E402

BUDGETS = [1, 2, 3, 5, 8, 12, 20, 40]
ALPHAS = [0.0, 0.25, 0.5, 0.75, 1.0]
AGGS = ["max", "mean"]
GRID_SETS = [(2,), (2, 3), (2, 3, 4)]


def variant_name(alpha, agg, grids):
    return "global" if alpha == 1.0 else f"a{alpha:g}_{agg}_g{''.join(map(str, grids))}"


def evaluate_scores(S, G, small, src_of_img, k_list=BUDGETS):
    """Selection metrics for a score matrix S (N, C) vs GT presence G (N, C)."""
    ranks = np.argsort(np.argsort(-S, axis=1, kind="stable"), axis=1)
    res = {"ranking_mAP": float(np.nanmean([class_ap(S[:, j], G[:, j]) for j in range(S.shape[1])]))}
    per_image = {}
    for k in k_list:
        sel = ranks < k
        rec = (sel & G).sum(1) / G.sum(1)
        per_image[k] = rec
        d = {"vocab_recall": float(rec.mean()), "pair_recall": float(sel[G].mean()),
             "pair_recall_small": float(sel[G & small].mean()), "pair_recall_not_small": float(sel[G & ~small].mean())}
        for s in sorted(set(src_of_img)):
            m = (np.array(src_of_img) == s)[:, None] & G & small
            if m.sum() >= 20:
                d[f"pair_recall_small_{s}"] = float(sel[m].mean())
        res[str(k)] = d
    return res, per_image


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--split", default="dev")
    args = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    sel_dir = REPO_ROOT / "outputs" / "selection" / args.split
    files = sorted(sel_dir.glob("views_*.npz"))
    if not files:
        print("no views_*.npz found; run scripts/run_views.py first", file=sys.stderr)
        return 1
    rows = {int(r["image_id"]): r for r in load_manifest() if r["split"] == args.split}
    gt = json.loads((get_store() / "datasets" / "LAE-80C-clean" / f"{args.split}.json").read_text(encoding="utf-8"))
    areas = defaultdict(list)
    for a in gt["annotations"]:
        areas[(a["image_id"], a["category_id"])].append(a["bbox"][2] * a["bbox"][3])

    out = {"split": args.split, "selection_rule": "D28: max class-wise ranking mAP; ties -> fewer crops, higher alpha, max",
           "models": {}}
    fig_data = {}
    L = [f"# M5 global + local selection ({args.split}; generated by `scripts/m5_global_local.py`)", "",
         "Scores per view = softmax over the 80 classes of logit_scale × cosine. Variant `aA_AGG_gGRIDS`: "
         "A·p_global + (1−A)·AGG over crops in GRIDS. `global` = M4 whole-image selector. "
         "Small pair = (image, class) whose objects in that image have median area < 32² px.", ""]
    for f in files:
        z = np.load(f)
        meta = json.loads(str(z["meta"]))
        model = meta["model"]
        ids, cat_ids = z["image_ids"], z["cat_ids"]
        cidx = {int(c): i for i, c in enumerate(cat_ids)}
        valid = ~np.isnan(z["global_logits"]).any(1)
        G = np.zeros((len(ids), len(cat_ids)), bool)
        small = np.zeros_like(G)
        for i, iid in enumerate(ids):
            for c in rows[int(iid)]["classes"].split():
                j = cidx[int(c)]
                G[i, j] = True
                small[i, j] = float(np.median(areas[(int(iid), int(c))])) < 1024
        src = [rows[int(i)]["source"] for i in ids]
        variants = [(1.0, "max", GRID_SETS[-1])] + [(a, g, gr) for a, g, gr in itertools.product(ALPHAS[:-1], AGGS, GRID_SETS)]
        results, per_img, scores = {}, {}, {}
        for alpha, agg, grids in variants:
            name = variant_name(alpha, agg, grids)
            S = np.full((len(ids), len(cat_ids)), -np.inf)
            for i in np.where(valid)[0]:
                S[i] = combine_views(z["global_logits"][i], z["crop_logits"][i], z["crop_grid_ids"], alpha, agg, grids)
            r, pi = evaluate_scores(S, G, small, src)
            r.update({"alpha": alpha, "agg": agg, "grids": list(grids), "n_crops": int(np.isin(z["crop_grid_ids"], grids).sum())})
            results[name], per_img[name], scores[name] = r, pi, S
        # D28 selection
        def key(n):
            r = results[n]
            return (r["ranking_mAP"], -r["n_crops"] if n != "global" else 0, r["alpha"], r["agg"] == "max")
        cands = [n for n in results if n != "global"]
        best = max(cands, key=key)
        local = [n for n in results if results[n]["alpha"] == 0.0]
        best_local = max(local, key=key)
        boot = {f"{best}_minus_global": {str(k): paired_mean_bootstrap(per_img["global"][k], per_img[best][k]) for k in (3, 8, 20)}}
        # image-level bootstrap of small-pair recall at k=8 (pairs grouped by image)
        rng = np.random.default_rng(0)
        rk = {n: np.argsort(np.argsort(-scores[n], axis=1, kind="stable"), axis=1) < 8 for n in ("global", best)}
        hits = {n: ((rk[n] & G & small).sum(1)) for n in rk}
        nsm = (G & small).sum(1)
        diffs = []
        for _ in range(2000):
            s = rng.integers(0, len(ids), len(ids))
            diffs.append(hits[best][s].sum() / nsm[s].sum() - hits["global"][s].sum() / nsm[s].sum())
        lo, hi = np.quantile(diffs, [0.025, 0.975])
        boot["small_pair_recall_k8"] = {"diff": float(hits[best].sum() / nsm.sum() - hits["global"].sum() / nsm.sum()),
                                        "ci_low": float(lo), "ci_high": float(hi), "excludes_zero": bool(lo > 0 or hi < 0)}
        out["models"][model] = {"views_meta": meta, "variants": results, "chosen": best, "best_local_only": best_local,
                                "bootstrap": boot, "views_ms_median": float(np.nanmedian(z["image_ms"]))}
        fig_data[model] = (results, best, best_local)

        for name, tag in ((best, "gl"), (best_local, "local")):
            r = results[name]
            np.savez_compressed(sel_dir / f"{model}_{tag}.npz", image_ids=ids, cat_ids=cat_ids, scores=scores[name],
                                image_ms=z["image_ms"],
                                meta=json.dumps({"selector": f"{model}_{tag}", "variant": name, "alpha": r["alpha"],
                                                 "agg": r["agg"], "grids": r["grids"], "n_crops": r["n_crops"],
                                                 "views_file": f.relative_to(REPO_ROOT).as_posix(),
                                                 "views_git_commit": meta["git_commit"],
                                                 "views_git_dirty_code": meta["git_dirty_code"],
                                                 "split": args.split, "device": meta["device"], "host": meta["host"],
                                                 "rule": out["selection_rule"],
                                                 "timing_note": "image_ms covers ALL views (1 + 29 crops), not only those used"}))

        # tables
        L += [f"## {model}", "", f"Chosen by D28: **`{best}`** · best local-only: `{best_local}` · "
              f"views per image: 1 + {meta['n_crops']} · CPU ms/img (all views) {out['models'][model]['views_ms_median']:.0f}", "",
              "| variant | crops | ranking mAP | recall k=3 | k=8 | k=20 | small-pair recall k=8 | not-small k=8 |",
              "|---|---|---|---|---|---|---|---|"]
        order = ["global"] + sorted(cands, key=lambda n: -results[n]["ranking_mAP"])
        for n in order[:12]:
            r = results[n]
            mark = " **(chosen)**" if n == best else (" (best local)" if n == best_local else "")
            L.append(f"| {n}{mark} | {r['n_crops'] if n != 'global' else 0} | {r['ranking_mAP']:.3f} | {r['3']['vocab_recall']:.3f} "
                     f"| {r['8']['vocab_recall']:.3f} | {r['20']['vocab_recall']:.3f} | {r['8']['pair_recall_small']:.3f} "
                     f"| {r['8']['pair_recall_not_small']:.3f} |")
        L += ["", f"(top 12 of {len(results)} variants by ranking mAP; all variants are in `m5_metrics.json`)", "",
              "Small-pair recall at k=8 by source (sources with ≥ 20 small pairs):", "",
              "| variant | " + " | ".join(k.replace("pair_recall_small_", "") for k in results["global"]["8"] if k.startswith("pair_recall_small_")) + " |",
              "|---|" + "---|" * sum(k.startswith("pair_recall_small_") for k in results["global"]["8"])]
        for n in ("global", best, best_local):
            L.append(f"| {n} | " + " | ".join(f"{v:.3f}" for k, v in results[n]["8"].items() if k.startswith("pair_recall_small_")) + " |")
        L += ["", "Paired image-level bootstrap (2000 resamples, 95% CI), chosen minus global:", ""]
        for k, v in boot[f"{best}_minus_global"].items():
            L.append(f"- vocabulary recall k={k}: {v['diff']:+.3f} [{v['ci_low']:+.3f}, {v['ci_high']:+.3f}]" + (" *" if v["excludes_zero"] else ""))
        v = boot["small_pair_recall_k8"]
        L.append(f"- small-pair recall k=8: {v['diff']:+.3f} [{v['ci_low']:+.3f}, {v['ci_high']:+.3f}]" + (" *" if v["excludes_zero"] else ""))
        L.append("")

    mdir = REPO_ROOT / "outputs" / "metrics" / f"m5_selection_{args.split}"
    mdir.mkdir(parents=True, exist_ok=True)
    (mdir / "m5_metrics.json").write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8", newline="\n")
    gen = REPO_ROOT / "reports" / "generated" / "M5_selection_tables.md"
    gen.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
    styles = {"global": "-", "chosen": "-", "local": "--"}
    for model, (res, best, bl) in fig_data.items():
        for n, lab in (("global", "global"), (best, "global+local"), (bl, "local only")):
            for ax, key in ((axes[0], "vocab_recall"), (axes[1], "pair_recall_small")):
                ax.plot(BUDGETS, [res[n][str(k)][key] for k in BUDGETS], marker="o", ms=3,
                        ls=styles["local" if lab == "local only" else "global"], label=f"{model}: {lab}")
    for ax, t in ((axes[0], "mean vocabulary recall"), (axes[1], "recall of small-object (image, class) pairs")):
        ax.set_xscale("log")
        ax.set_xticks(BUDGETS, [str(k) for k in BUDGETS])
        ax.set_xlabel("budget k")
        ax.set_ylabel(t)
        ax.grid(alpha=0.3)
    axes[0].legend(fontsize=7)
    fig.suptitle(f"LAE-80C {args.split}: global vs local vs global+local selection")
    fig.tight_layout()
    (REPO_ROOT / "outputs" / "figures").mkdir(parents=True, exist_ok=True)
    fig.savefig(REPO_ROOT / "outputs" / "figures" / f"m5_recall_{args.split}.png", dpi=150)
    print(gen.read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
