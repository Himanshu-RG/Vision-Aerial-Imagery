"""Paired comparison of selector conditions against a chosen reference condition at matched k,
computed from a committed metrics.json (no predictions needed): AP50 differences, per-class sign test,
small-object recall/AP and per-source AP50.

Usage:
    python scripts/compare_conditions.py outputs/metrics/<run_id> --pairs sel:A:k8=sel:B:k8 [...] --out NAME
Writes reports/generated/<NAME>.md
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics as st
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "scripts"))
from report_run import sign_test  # noqa: E402

SOURCES = ("FAIR-18C", "Xview-34C", "DIOR-18C", "DOTA-6C")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("metrics_dir", type=Path)
    ap.add_argument("--pairs", nargs="+", required=True, help="REFERENCE=CANDIDATE condition pairs")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    m = json.loads((args.metrics_dir / "metrics.json").read_text(encoding="utf-8"))
    src = {r["category_id"]: r["source"] for r in csv.DictReader((REPO_ROOT / "data/manifests/lae80c_vocabulary.csv").open(encoding="utf-8"))}
    C = m["conditions"]

    def bysrc(c, p):
        pc = C[c][p]["per_class"]
        return [st.mean([d["AP50"] for k, d in pc.items() if src[k] == s]) for s in SOURCES]

    L = [f"# {args.out} (generated by `scripts/compare_conditions.py` from `{args.metrics_dir.as_posix()}`)", "",
         "Point differences and per-class paired sign test (two-sided exact binomial) of candidate vs reference. "
         "No bootstrap (predictions not needed). AP50 at maxDets 900.", "",
         "| reference → candidate | protocol | AP50 ref → cand (Δ) | classes better / worse | sign-test p | R50 small ref → cand | AP50 small ref → cand | per-source AP50 " + "/".join(s[:4] for s in SOURCES) + " ref → cand |",
         "|---|---|---|---|---|---|---|---|"]
    for pair in args.pairs:
        ref, cand = pair.split("=")
        for p in ("source_aware", "standard"):
            a, b = C[ref][p], C[cand][p]
            pos, neg, pv = sign_test(m, cand, ref, p)
            L.append(f"| `{ref}` → `{cand}` | {p} | {a['AP50@900']:.4f} → {b['AP50@900']:.4f} ({b['AP50@900'] - a['AP50@900']:+.4f}) "
                     f"| {pos} / {neg} | {pv:.3g} | {a['R50_small']:.3f} → {b['R50_small']:.3f} | {a['AP50_small']:.3f} → {b['AP50_small']:.3f} "
                     f"| {'/'.join(f'{v:.3f}' for v in bysrc(ref, p))} → {'/'.join(f'{v:.3f}' for v in bysrc(cand, p))} |")
    out = REPO_ROOT / "reports" / "generated" / f"{args.out}.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(out.read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
