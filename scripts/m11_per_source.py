"""M11 part 1: per-source generalization on dev, computed from committed metrics (no predictions needed).

Under the source-aware protocol each class has GT and kept predictions only on its own source's images, so the
mean per-class AP50 over a source's classes is exactly that source's AP50. Standard-protocol per-class AP also
counts that class's false positives on other sources' images, and is reported for completeness.
Per source and condition: mean AP50 over the source's classes with GT, and a per-class sign test vs `full`.

Usage:
    python scripts/m11_per_source.py [outputs/metrics/<run_id>]   (default: the E5 run, which has every main condition)
Writes reports/generated/M11_per_source_<run name>.md and outputs/metrics/m11_per_source/<run_id>.json
"""

from __future__ import annotations

import csv
import json
import sys
from collections import defaultdict
from math import comb
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT = REPO_ROOT / "outputs/metrics/e5_caption_tagclip_det-69e357c3b1f4"
SOURCES = ("DIOR-18C", "DOTA-6C", "FAIR-18C", "PP-4C", "Xview-34C")


def sign(a: list[float], b: list[float]) -> tuple[int, int, float]:
    pos = sum(y - x > 1e-12 for x, y in zip(a, b))
    neg = sum(y - x < -1e-12 for x, y in zip(a, b))
    n = pos + neg
    p = 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, i) for i in range(min(pos, neg) + 1)) / 2 ** n)
    return pos, neg, p


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    mdir = (Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT).resolve()
    m = json.loads((mdir / "metrics.json").read_text(encoding="utf-8"))
    cfg = json.loads((mdir / "run_config.json").read_text(encoding="utf-8"))
    src = {r["category_id"]: r["source"] for r in csv.DictReader((REPO_ROOT / "data/manifests/lae80c_vocabulary.csv").open(encoding="utf-8"))}
    rows = {r["image_id"]: r for r in csv.DictReader((REPO_ROOT / "data/manifests/lae80c_manifest.csv").open(encoding="utf-8"))}
    ids = cfg["image_ids"]
    n_img, n_obj = defaultdict(int), defaultdict(int)
    for i in ids:
        r = rows[str(i)]
        n_img[r["source"]] += 1
        n_obj[r["source"]] += int(r["n_boxes"])
    conds = cfg["config"]["conditions"]
    out = {"run_id": m["run_id"], "n_images": len(ids), "per_source": {}}
    for s in SOURCES:
        out["per_source"][s] = {"n_images": n_img[s], "n_objects": n_obj[s], "conditions": {}}
        for proto in ("source_aware", "standard"):
            pc_full = m["conditions"]["full"][proto]["per_class"]
            keys = sorted(k for k in pc_full if src[k] == s)
            for c in conds:
                pc = m["conditions"][c][proto]["per_class"]
                a, b = [pc_full[k]["AP50"] for k in keys], [pc[k]["AP50"] for k in keys]
                pos, neg, p = sign(a, b)
                out["per_source"][s]["conditions"].setdefault(c, {})[proto] = {
                    "n_classes": len(keys), "AP50": sum(b) / len(b) if b else None, "better_worse_vs_full": [pos, neg], "sign_p": p}
    dst = REPO_ROOT / "outputs/metrics/m11_per_source"
    dst.mkdir(parents=True, exist_ok=True)
    (dst / f"{m['run_id']}.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8", newline="\n")
    L = [f"# M11 per-source AP50 (generated by `scripts/m11_per_source.py` from `{mdir.relative_to(REPO_ROOT).as_posix()}`)", "",
         f"{len(ids)} dev images. Cell = mean AP50 (maxDets 900) over the source's classes with GT; under source-aware scoring this "
         "equals the source's own AP50. In brackets: classes better / worse than `full`, per-class sign-test p.", ""]
    for proto in ("source_aware", "standard"):
        L += [f"## {proto}", "", "| condition | " + " | ".join(f"{s} ({n_img[s]} img, {n_obj[s]} obj)" for s in SOURCES) + " |",
              "|---" * (len(SOURCES) + 1) + "|"]
        for c in conds:
            cells = []
            for s in SOURCES:
                r = out["per_source"][s]["conditions"][c][proto]
                if r["AP50"] is None:
                    cells.append("–")
                elif c == "full":
                    cells.append(f"{r['AP50']:.4f} ({r['n_classes']} cl.)")
                else:
                    cells.append(f"{r['AP50']:.4f} ({r['better_worse_vs_full'][0]}/{r['better_worse_vs_full'][1]}, p={r['sign_p']:.2g})")
            L.append(f"| {c} | " + " | ".join(cells) + " |")
        L.append("")
    out_md = REPO_ROOT / f"reports/generated/M11_per_source_{cfg['config']['name']}.md"
    out_md.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(out_md.read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
