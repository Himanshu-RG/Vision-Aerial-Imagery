"""M10: object-weighted vs image-averaged vocabulary coverage, and the cross-source synonym diagnostic (no detector).

Usage:
    python scripts/m10_vocab_coverage.py
For the 200 E0/E5 evaluation images: share of GT *objects* whose class is in the selected vocabulary, against the
image-averaged class recall used so far (M4-M6), per source; share of selected classes outside the image's source
label space; and a DIAGNOSTIC (uses source identity, never a method): RemoteCLIP top-8 restricted to the image's
source label space. Writes outputs/metrics/m10_failure/vocab_coverage.json and reports/generated/M10_vocab_coverage.md.
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from aerial_ovd.utils.paths import get_store  # noqa: E402
from aerial_ovd.vocabulary.retention import topk  # noqa: E402

RUN = "e5_caption_tagclip_det-69e357c3b1f4"


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    gt = json.loads((get_store() / "datasets/LAE-80C-clean/dev.json").read_text(encoding="utf-8"))
    ids = json.loads((REPO_ROOT / f"outputs/metrics/{RUN}/run_config.json").read_text(encoding="utf-8"))["image_ids"]
    vocab = list(csv.DictReader((REPO_ROOT / "data/manifests/lae80c_vocabulary.csv").open(encoding="utf-8")))
    cat_src = {int(v["category_id"]): v["source"] for v in vocab}
    name = {int(v["category_id"]): v["raw_name"] for v in vocab}
    src = {im["id"]: im["file_name"].split("_")[0] for im in gt["images"]}
    idset = set(ids)
    objs = defaultdict(Counter)
    for a in gt["annotations"]:
        if a["image_id"] in idset:
            objs[a["image_id"]][a["category_id"]] += 1

    sel = REPO_ROOT / "outputs/selection/dev"
    rc = np.load(sel / "remoteclip_b32.npz")
    cat = [int(c) for c in rc["cat_ids"]]
    row = {int(i): j for j, i in enumerate(rc["image_ids"])}

    def mask(f):
        z = np.load(sel / f"{f}.npz")
        assert [int(c) for c in z["cat_ids"]] == cat and [int(i) for i in z["image_ids"]] == list(row)
        return z["selected"]

    in_src = np.array([[cat_src[c] == src[i] for c in cat] for i in row])
    restricted = []
    for i, j in row.items():
        s = np.where(in_src[j], rc["scores"][j], -np.inf)
        restricted.append(topk(s, min(8, int(in_src[j].sum()))))
    masks = {"RemoteCLIP top-8": np.stack([topk(s, 8) for s in rc["scores"]]),
             "headline (threshold m≈8)": mask("m6_threshold_m8"),
             "caption threshold m≈8": mask("e5_caption_thr_m8"),
             "DIAGNOSTIC: RemoteCLIP top-8 within source label space": np.stack(restricted)}
    out = {"run_image_sample": RUN, "n_images": len(ids), "n_objects": int(sum(sum(c.values()) for c in objs.values())), "selectors": {}}
    for k, M in masks.items():
        hit = tot = 0
        img, per, oos, picked = [], defaultdict(lambda: [0, 0]), [], Counter()
        for i in ids:
            j = row[i]
            chosen = {cat[x] for x in np.where(M[j])[0]}
            h, t = sum(n for c, n in objs[i].items() if c in chosen), sum(objs[i].values())
            hit, tot = hit + h, tot + t
            per[src[i]][0] += h
            per[src[i]][1] += t
            img.append(float(np.mean([c in chosen for c in objs[i]])))
            oos.append(sum(cat_src[c] != src[i] for c in chosen) / max(1, len(chosen)))
            picked.update((name[c], cat_src[c], src[i]) for c in chosen if cat_src[c] != src[i])
        out["selectors"][k] = {"object_weighted_recall": hit / tot, "image_mean_recall": float(np.mean(img)),
                               "selected_out_of_source_share": float(np.mean(oos)),
                               "object_weighted_recall_by_source": {s: a / b for s, (a, b) in sorted(per.items())},
                               "top_out_of_source_picks": [{"class": c, "class_source": cs, "image_source": s, "n_images": n}
                                                           for (c, cs, s), n in picked.most_common(10)]}
    dst = REPO_ROOT / "outputs/metrics/m10_failure/vocab_coverage.json"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8", newline="\n")
    srcs = sorted({src[i] for i in ids})
    L = ["# M10 vocabulary coverage (generated by `scripts/m10_vocab_coverage.py`)", "",
         f"{out['n_images']} dev images, {out['n_objects']} GT objects. Object-weighted = share of GT objects whose class is selected; "
         "image mean = per-image share of present classes (the M4–M6 metric).", "",
         "| selector | object-weighted | image mean | selected classes outside source | " + " | ".join(srcs) + " |", "|---" * (4 + len(srcs)) + "|"]
    for k, r in out["selectors"].items():
        L.append(f"| {k} | {r['object_weighted_recall']:.3f} | {r['image_mean_recall']:.3f} | {r['selected_out_of_source_share']:.2f} | "
                 + " | ".join(f"{r['object_weighted_recall_by_source'][s]:.2f}" for s in srcs) + " |")
    L += ["", "Most frequent out-of-source picks of the headline selector (class [its source] on images of source: n images):", ""]
    L += [f"- {p['class']} [{p['class_source']}] on {p['image_source']}: {p['n_images']}" for p in out["selectors"]["headline (threshold m≈8)"]["top_out_of_source_picks"]]
    (REPO_ROOT / "reports/generated/M10_vocab_coverage.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
