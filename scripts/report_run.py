"""Generate a Markdown results table for any evaluated detection run (no hand-typed numbers).

Usage:
    python scripts/report_run.py outputs/metrics/<run_id>   # writes reports/generated/<run_name>_tables.md
Rows follow the condition order of the run's config. Oracle diagnostics are marked.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ORACLE = {"oracle_gt", "oracle_source", "random_matched"}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("metrics_dir", type=Path)
    args = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    m = json.loads((args.metrics_dir / "metrics.json").read_text(encoding="utf-8"))
    cfg = json.loads((args.metrics_dir / "run_config.json").read_text(encoding="utf-8"))
    boot = m.get("bootstrap", {})
    L = [f"# {cfg['config']['name']} tables (generated by `scripts/report_run.py` from `{args.metrics_dir.as_posix()}`)", "",
         f"run `{m['run_id']}` · host `{cfg['host']}` · git `{cfg['git_commit'][:7]}` (dirty={cfg['git_dirty']}) · "
         f"torch {cfg['torch']} · split `{cfg['config']['split']}` · {len(cfg['image_ids'])} images · "
         f"bootstrap n={boot.get('n_boot')} vs `{boot.get('reference')}`", "",
         "`(oracle)` = uses ground-truth information; a diagnostic, never a method. "
         "Δ = paired bootstrap AP50@900 difference vs the reference with 95% percentile CI; `*` = CI excludes 0.", "",
         "| condition | vocab | tokens | failed | AP50@900 std | Δ std | AP50@900 src-aware | Δ src-aware | AR@900 std "
         "| R50 small | latency med ms |", "|---|---|---|---|---|---|---|---|---|---|---|"]

    def d(cond, proto):
        b = boot.get(cond, {})
        if not isinstance(b, dict) or proto not in b:
            return "ref" if cond == boot.get("reference") else "–"
        v = b[proto]
        return f"{v['diff_point']:+.4f} [{v['ci_low']:+.4f}, {v['ci_high']:+.4f}]" + ("*" if v["ci_excludes_zero"] else "")

    for cond in cfg["config"]["conditions"]:
        r = m["conditions"].get(cond)
        if r is None:
            continue
        s, a = r["standard"], r["source_aware"]
        label = cond + (" (oracle)" if cond in ORACLE else "")
        lat = (r.get("latency_ms") or {}).get("median")
        L.append(f"| {label} | {r['vocab_size_mean'] or 0:.1f} | {r['text_tokens_mean'] or 0:.0f} | {r['n_failed_or_missing']} "
                 f"| {s['AP50@900']:.4f} | {d(cond, 'standard')} | {a['AP50@900']:.4f} | {d(cond, 'source_aware')} "
                 f"| {s['AR@900']:.3f} | {s['R50_small']:.3f} | {lat if lat is None else round(lat)} |")
    out = REPO_ROOT / "reports" / "generated" / f"{cfg['config']['name']}_tables.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(out.read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
